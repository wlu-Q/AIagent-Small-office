// Real Desktop -> preload -> Gateway -> native task -> Git -> file-preview UI.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms))

exports.run = async ({ window, api, send, waitFor, reloadChat }) => {
  const evaluate = expression => window.webContents.executeJavaScript(expression)
  await evaluate("document.querySelector('[data-office-employee-editor-launcher]').click()")
  await waitFor("document.querySelector('[data-edit-employee-item=pm]')", 'PM editor entry')
  await evaluate("document.querySelector('[data-edit-employee-item=pm]').click()")
  await waitFor("document.querySelector('[data-edit-tool=write_todos]')", 'optional PM todo choice')
  assert.equal(await evaluate("!document.querySelector('[data-edit-tool=write_todos]').disabled && !document.querySelector('[data-edit-tool=write_todos]').checked"), true)
  assert.equal(await evaluate("!document.querySelector('[data-edit-tool=apply_patch]').disabled && document.querySelector('[data-edit-tool=powershell_terminal]').disabled && !document.querySelector('[data-edit-tool=powershell_terminal]').checked"), true)
  await evaluate("document.querySelector('[data-edit-tool=write_todos]').click(); document.querySelector('[data-edit-tool=apply_patch]').click()")
  await evaluate("document.querySelector('[data-save-employee]').click()")
  await waitFor("document.querySelector('.MuiSnackbar-root [role=alert]')?.textContent === '员工配置保存成功' && document.querySelector('[data-save-employee]')?.disabled === false", 'PM settings saved')
  const pmTools = await api('/api/office/employees/pm/tools')
  assert.ok(pmTools.availableTools.includes('write_todos') && pmTools.availableTools.includes('apply_patch'))
  assert.ok(!pmTools.availableTools.includes('powershell_run') && pmTools.availableTools.includes('capture_user_message'))
  await evaluate("document.querySelector('[data-close-employee-editor]').click(); document.querySelector('[data-office-employee-editor-launcher]').click()")
  await waitFor("document.querySelector('[data-edit-tool=write_todos]')?.checked && document.querySelector('[data-edit-tool=apply_patch]')?.checked", 'PM choices persisted')
  await evaluate("document.querySelector('[data-edit-tool=write_todos]').click(); document.querySelector('[data-edit-tool=apply_patch]').click(); document.querySelector('[data-save-employee]').click()")
  await waitFor("document.querySelector('.MuiSnackbar-root [role=alert]')?.textContent === '员工配置保存成功' && document.querySelector('[data-save-employee]')?.disabled === false", 'PM choices cleared')
  const cleared = await api('/api/office/employees/pm/tools')
  assert.ok(!cleared.availableTools.includes('write_todos') && !cleared.availableTools.includes('apply_patch'))
  await evaluate("document.querySelector('[data-close-employee-editor]').click()")
  await send('E2E_WORKTREE 两位员工各做一版 README，我想对比一下。')
  await waitFor("document.querySelector('[data-office-progressive-reply]')?.innerText.includes('我会让两位员工')", 'PM explains work before completion')
  assert.ok((await api('/api/office/employees/pm/runs?conversationKind=group')).runs.some(run => run.status === 'running'))
  await waitFor("document.querySelectorAll('[data-office-employee-progress][data-progress-message=shared-step-start]').length === 2", 'both employees show separate live prose', 20000)
  assert.equal(await evaluate("document.body.innerText.includes('E2E_WORKTREE_DONE')"), false)
  const liveRows = await evaluate("Array.from(document.querySelectorAll('[data-office-employee-progress]')).map(row => ({employee: row.dataset.officeEmployeeProgress, task: row.dataset.progressTask, avatar: row.querySelector('[data-sender-avatar]')?.dataset.senderAvatar, collapsed: Boolean(row.closest('details'))}))")
  assert.deepEqual(liveRows.map(row => row.employee).sort(), ['writer', 'writer2'])
  assert.equal(new Set(liveRows.map(row => row.task)).size, 2)
  assert.ok(liveRows.every(row => row.avatar && !row.collapsed))
  assert.equal(await evaluate("document.querySelector('[data-office-work-progress] > header > button')?.getAttribute('aria-expanded')"), 'true')
  assert.equal(await evaluate("Array.from(document.querySelectorAll('[data-office-employee-progress] [data-sender-avatar]')).every(node => node.textContent.trim().length === 1 && node.children.length === 0)"), true)
  await evaluate("document.querySelector('[data-office-work-progress] > header > button').click()")
  assert.equal(await evaluate("document.querySelector('[data-work-content]').hidden"), true)
  await evaluate("document.querySelector('[data-office-work-progress] > header > button').click()")
  assert.equal(await evaluate("document.querySelector('[data-work-content]').hidden"), false)
  fs.mkdirSync(path.resolve(__dirname, '../output/playwright'), { recursive: true })
  fs.writeFileSync(path.resolve(__dirname, '../output/playwright/employee-progress-live.png'), (await window.webContents.capturePage()).toPNG())
  await waitFor("document.body.innerText.includes('E2E_WORKTREE_DONE')", 'two isolated task results', 60000)
  await waitFor("document.querySelector('[data-group-message][data-message-role=assistant]')?.innerText.includes('E2E_WORKTREE_DONE')", 'final reply in saved history')
  await waitFor("(async () => { const {runs} = await window.officeDesktopBridge.listOfficeRuns('pm', 'group', 1); return runs[0]?.eventsFinalized === true && !runs[0]?.finalizing })()", 'Run events finalized')
  const { runs: completedRuns } = await evaluate("window.officeDesktopBridge.listOfficeRuns('pm', 'group', 1)")
  const completedRun = completedRuns[0]
  const finalEvents = await evaluate(`window.officeDesktopBridge.listOfficeRunEvents('pm', ${JSON.stringify(completedRun.runId)}, 0)`)
  assert.ok(finalEvents.nextAfterSeq >= completedRun.lastEventSeq)
  const expectedWorkers = finalEvents.events.filter(event => event.event_type === 'subagent.step'
    && event.content.kind === 'ai' && event.content.public_text?.trim())
    .map(event => [event.content.employee_id, event.content.task_id, event.content.message_id || `step:${event.content.message_index ?? event.seq}`])
  assert.equal(expectedWorkers.length, 4)
  const workerIdentities = "Array.from(document.querySelectorAll('[data-office-employee-progress]')).map(row => [row.dataset.officeEmployeeProgress, row.dataset.progressTask, row.dataset.progressMessage])"
  await waitFor(`JSON.stringify(${workerIdentities}) === ${JSON.stringify(JSON.stringify(expectedWorkers))}`, 'all finalized employee messages rendered')
  const proseState = () => evaluate("({workers: Array.from(document.querySelectorAll('[data-office-employee-progress]')).map(row => { const copy = row.cloneNode(true); copy.querySelectorAll('[data-office-file]').forEach(card => card.replaceWith(card.dataset.officeFile)); return [row.dataset.officeEmployeeProgress, row.dataset.progressTask, row.dataset.progressMessage, copy.textContent]; }), finals: Array.from(document.querySelectorAll('[data-office-progressive-reply], [data-message-role=assistant]')).filter(row => row.innerText.includes('E2E_WORKTREE_DONE')).length, hidden: document.body.innerText.includes('PRIVATE_EMPLOYEE_REASONING'), tools: document.querySelectorAll('[data-office-tool-group]').length})")
  const beforeReplay = await proseState()
  assert.equal(beforeReplay.finals, 1)
  assert.equal(beforeReplay.hidden, false)
  assert.ok(beforeReplay.tools > 0)
  await waitFor("document.querySelector('[data-office-work-progress] > header')?.innerText.startsWith('用时')", 'immutable end-to-end elapsed time')
  assert.equal(await evaluate("document.querySelector('[data-office-work-progress] > header > button')?.getAttribute('aria-expanded')"), 'true')
  assert.equal(await evaluate("Array.from(document.querySelectorAll('[data-group-message][data-message-role=assistant]')).filter(node => node.innerText.includes('E2E_WORKTREE_DONE')).every(node => !node.closest('[data-work-content]'))"), true)
  const finishedDuration = await evaluate("document.querySelector('[data-office-work-progress] > header').innerText")
  assert.equal(new Set(beforeReplay.workers.map(row => row.slice(0, 3).join(':'))).size, beforeReplay.workers.length)
  await evaluate("document.querySelector('[data-office-employee=writer]').click()")
  await waitFor("document.querySelector('[data-office-employee-progress]') === null", 'group prose never leaks into private chat')
  await evaluate("document.querySelector('[data-office-group]').click()")
  await waitFor("document.querySelectorAll('[data-office-employee-progress]').length === " + beforeReplay.workers.length, 'cached group prose restored')
  assert.deepEqual((await proseState()).workers, beforeReplay.workers)
  await reloadChat()
  try {
    await waitFor("document.querySelectorAll('[data-office-employee-progress]').length === " + beforeReplay.workers.length, 'persisted employee prose restored', 30000)
  } catch (error) {
    console.log('PROSE_REPLAY_DIAGNOSTIC', JSON.stringify({ before: beforeReplay, after: await proseState() }))
    throw error
  }
  await waitFor("document.querySelector('[data-group-message][data-message-role=assistant]')?.innerText.includes('E2E_WORKTREE_DONE')", 'persisted final reply restored')
  const afterReplay = await proseState()
  assert.deepEqual(afterReplay.workers, beforeReplay.workers)
  assert.equal(afterReplay.finals, 1)
  assert.equal(afterReplay.hidden, false)
  assert.equal(await evaluate("document.querySelector('[data-office-work-progress] > header').innerText"), finishedDuration)
  assert.equal(await evaluate("document.querySelector('[data-office-work-progress] > header > button')?.getAttribute('aria-expanded')"), 'false')
  await evaluate("document.querySelector('[data-office-work-progress] > header > button').click()")
  const { workspaces, source, status } = await api('/test-workspaces')
  const written = workspaces.filter(w => w.root_path)
  assert.equal(written.length, 2)
  assert.equal(new Set(written.map(w => w.root_path)).size, 2)
  assert.equal(new Set(written.map(w => w.baseline_commit)).size, 1)
  assert.ok(written.every(w => !('integration_status' in w)))
  for (const workspace of written) {
    assert.equal(path.resolve(workspace.root_path), path.resolve(workspace.project_path, '.office-worktrees', workspace.workspace_id, 'tree'))
    assert.ok(fs.existsSync(path.join(workspace.project_path, '.office-worktrees', workspace.workspace_id, 'outputs')))
    assert.ok(!fs.existsSync(path.join(workspace.root_path, '.office-worktrees')))
  }
  assert.equal(source, '# 临时联调项目\n')
  assert.equal(status, '')
  assert.deepEqual(written.map(w => fs.readFileSync(path.join(w.root_path, 'README.md'), 'utf8').replace(/\r\n/g, '\n')).sort(), ['# WORKTREE_A\n', '# WORKTREE_B\n'])
  assert.ok(!workspaces.some(w => w.employee_id === 'pm'), 'PM has no implicit workspace')
  await waitFor("document.querySelector('[data-office-file^=\"/mnt/office-workspaces/\"]')", 'scoped file link')
  await evaluate("document.querySelector('[data-office-file^=\"/mnt/office-workspaces/\"]').click()")
  await waitFor("document.querySelector('[data-office-file-preview]')", 'task file preview')
  await waitFor("/WORKTREE_[AB]/.test(document.querySelector('[data-office-file-preview]')?.innerText || '')", 'actual task preview contents loaded')
  const previewText = await evaluate("document.querySelector('[data-office-file-preview]').innerText")
  assert.match(previewText, /WORKTREE_[AB]/)
  await evaluate("document.querySelector('[data-office-file-preview] button[aria-label=\"关闭文件预览\"]').click()")

  await evaluate("document.querySelector('[data-office-employee=\"writer\"]').click()")
  await send('E2E_EMPLOYEE E2E_WORKTREE_DIRECT 帮我改一下 README，完成后问我一声。')
  await waitFor("document.querySelector('[data-office-human-input]')", 'direct task ask after write', 45000)
  assert.equal(await evaluate("document.querySelectorAll('[data-office-work-progress]').length"), 1)
  assert.equal(await evaluate("document.querySelector('[data-office-human-input]').closest('[data-work-content]') === null"), true)
  assert.equal(await evaluate("(() => { const prose = Array.from(document.querySelectorAll('[data-message-role=assistant], [data-office-progressive-reply]')).find(row => row.innerText.includes('我先读取当前项目')); const tool = document.querySelector('[data-office-tool-group]'); return Boolean(prose && tool && (prose.compareDocumentPosition(tool) & Node.DOCUMENT_POSITION_FOLLOWING)); })()"), true)
  const before = (await api('/test-workspaces')).workspaces.find(w => w.owner_key === 'direct:writer')
  assert.equal(before, undefined)
  assert.equal((await api('/test-workspaces')).source, '# WORKTREE_DIRECT\n')
  // Normal text reply through the same real input must resume, not create a new workspace.
  await send('E2E_EMPLOYEE 可以，再看一眼就行。')
  await waitFor("document.body.innerText.includes('WORKTREE_DIRECT_DONE')", 'resumed task reads its own modified file', 45000)
  assert.equal(await evaluate("document.querySelectorAll('[data-office-work-progress]').length"), 1)
  assert.equal(await evaluate("document.body.innerText.includes('PRIVATE_EMPLOYEE_REASONING')"), false)
  assert.equal(await evaluate("Array.from(document.querySelectorAll('[data-message-role=assistant], [data-office-progressive-reply]')).filter(row => row.innerText.includes('我先读取当前项目')).length"), 1)
  const after = (await api('/test-workspaces')).workspaces.filter(w => w.owner_key === 'direct:writer')
  assert.equal(after.length, 0)
  assert.equal((await api('/test-workspaces')).source, '# WORKTREE_DIRECT\n')
  const deadline = Date.now() + 10000
  while (Date.now() < deadline && (await api('/api/office/employees')).employees.some(e => e.state === 'working')) await sleep(100)
  assert.ok((await api('/api/office/employees')).employees.every(e => e.state === 'idle'))
  assert.equal((await api('/api/office/queue')).items.length, 0)
  await evaluate("document.querySelector('[data-office-group]').click()")
  await send('E2E_ROUND_PARTIAL 前一位没做完的话，让另一位接着做，不要重写。')
  await waitFor("document.body.innerText.includes('E2E_ROUND_PARTIAL_DONE')", 'partial result continued by another employee', 60000)
  const partialFacts = await api('/test-workspaces')
  const stopped = partialFacts.receipts.find(item => item.status === 'timeout')
  assert.ok(stopped, 'predecessor remains timed out')
  const stoppedRef = JSON.parse(stopped.result_ref_json)
  assert.equal(stoppedRef.stop_reason, 'round_timeout')
  assert.equal(Object.hasOwn(stoppedRef, 'result_commit'), false, 'task completion does not freeze a result commit')
  const successor = partialFacts.workspaces.find(item => item.workspace_id === stoppedRef.workspace_id)
  assert.ok(successor)
  assert.equal(execFileSync('git', ['-C', successor.root_path, 'rev-parse', 'HEAD'], {
    encoding: 'utf8', windowsHide: true,
  }).trim(), stoppedRef.baseline_commit, 'continuation keeps ordinary edits on the same worktree')
  const continued = partialFacts.receipts.find(item => item.employee_id === 'writer2' && item.status === 'succeeded' && JSON.parse(item.result_ref_json).workspace_id === stoppedRef.workspace_id)
  assert.ok(continued)
  assert.equal(fs.readFileSync(path.join(successor.root_path, 'README.md'), 'utf8').replace(/\r\n/g, '\n'), '# PARTIAL_BASE\nCONTINUED\n')
  assert.equal(partialFacts.source, '# WORKTREE_DIRECT\n')
  await evaluate("document.querySelector('[data-office-employee=\"writer\"]').click()")
  await send('E2E_EMPLOYEE E2E_ROUND_TIMEOUT 测试单轮执行超时。')
  let timeoutRun
  const timeoutDeadline = Date.now() + 15000
  while (Date.now() < timeoutDeadline) {
    timeoutRun = (await api('/api/office/employees/writer/runs?conversationKind=private')).runs[0]
    if (timeoutRun?.status === 'timeout') break
    await sleep(100)
  }
  assert.equal(timeoutRun?.status, 'timeout')
  assert.match(timeoutRun.error, /本轮.*900/)
  const settledDeadline = Date.now() + 10000
  while (Date.now() < settledDeadline && (await api('/api/office/employees')).employees.some(item => item.state === 'working')) await sleep(100)
  assert.ok((await api('/api/office/employees')).employees.every(item => item.state === 'idle'))
  assert.equal((await api('/api/office/queue')).items.length, 0)
  const output = path.resolve(__dirname, '../output/playwright')
  fs.mkdirSync(output, { recursive: true })
  fs.writeFileSync(path.join(output, 'stage3-workspaces.png'), (await window.webContents.capturePage()).toPNG())
  fs.writeFileSync(path.join(output, 'stage3-workspaces.json'), JSON.stringify(await api('/test-workspaces'), null, 2))
  console.log('TASK_WORKSPACES_UI_OK', JSON.stringify({ parallel: written.map(w => w.workspace_id), directResumedInProject: true, continuation: successor.workspace_id }))
}
