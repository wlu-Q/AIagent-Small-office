const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')

exports.run = async (window, wait, fixture) => {
  const evaluate = value => window.webContents.executeJavaScript(value)
  const click = selector => evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`)
  const open = async () => {
    await click('[data-office-employee-editor-launcher]')
    await wait(window, `document.querySelector('[data-edit-employee-item="frontend-one"]')`, 'employee list')
    await click('[data-edit-employee-item="frontend-one"]')
    await wait(window, `document.querySelector('[data-edit-employee-model] [role="button"]')?.getAttribute('aria-disabled') !== 'true' && document.querySelector('[data-edit-employee-prompt]')`, 'model dropdown loaded')
  }
  const choose = async id => {
    await evaluate(`document.querySelector('[data-edit-employee-model] [role="button"]').dispatchEvent(new MouseEvent('mousedown',{bubbles:true,button:0}))`)
    await wait(window, `document.querySelector('[data-employee-model-option="${id}"]')`, 'model menu')
    await click(`[data-employee-model-option="${id}"]`)
    await wait(window, `!document.querySelector('[role="listbox"]')`, 'menu closed')
  }
  await open()
  assert.equal(await evaluate(`document.querySelector('[data-edit-employee-model]').textContent.includes('OpenAI - gpt-existing - 高')`), true)
  await choose('model-1')
  assert.equal(fixture.getSaved().modelProfileId, 'model-0')
  await click('[data-close-employee-editor]')
  await open()
  assert.equal(await evaluate(`document.querySelector('[data-edit-employee-model]').textContent.includes('gpt-existing')`), true)
  await choose('model-1')
  fixture.failSave(true)
  await click('[data-save-employee]')
  await wait(window, `document.querySelector('.MuiSnackbar-root [role=alert]')?.textContent.includes('保存失败测试')`, 'failed save')
  assert.equal(fixture.getSaved().modelProfileId, 'model-0')
  assert.equal(await evaluate(`document.querySelector('[data-edit-employee-model]').textContent.includes('team-model-1')`), true)
  fixture.failSave(false)
  await click('[data-save-employee]')
  await wait(window, `document.querySelector('.MuiSnackbar-root [role=alert]')?.textContent === '员工配置保存成功' && document.querySelector('[data-save-employee]')?.disabled === false`, 'saved')
  assert.equal(fixture.getSaved().modelProfileId, 'model-1')
  fixture.setWorking(true)
  await wait(window, `document.querySelector('[data-edit-employee-model] [role="button"]')?.getAttribute('aria-disabled') === 'true' && document.querySelector('[data-save-employee]').disabled`, 'busy blocks model selection')
  fixture.setWorking(false)
  await wait(window, `!document.querySelector('[data-save-employee]').disabled`, 'idle unlocks')
  await evaluate(`document.querySelector('[data-edit-employee-model]').scrollIntoView({block:'center'})`)
  await evaluate(`document.querySelector('[data-edit-employee-model] [role="button"]').dispatchEvent(new MouseEvent('mousedown',{bubbles:true,button:0}))`)
  await wait(window, `document.querySelectorAll('[data-employee-model-option]').length === 8`, 'all registered options')
  await new Promise(resolve => setTimeout(resolve, 400))
  const folder = path.resolve(__dirname, '../output/employee-model')
  await fs.mkdir(folder, { recursive: true })
  await fs.writeFile(path.join(folder, 'dropdown.png'), (await window.webContents.capturePage()).toPNG())
  await click('[data-employee-model-option="model-1"]')
  await click('[data-close-employee-editor]')
  await open()
  assert.equal(await evaluate(`document.querySelector('[data-edit-employee-model]').textContent.includes('team-model-1')`), true)
  console.log('EMPLOYEE_MODEL_UI_OK: draft, discard, failed save, persisted save, working disabled, reopen')
}
