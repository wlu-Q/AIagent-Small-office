const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')

module.exports = async (window, wait, setValue, selectLanguage) => {
  const evaluate = expression => window.webContents.executeJavaScript(expression)
  const query = selector => 'document.querySelector(' + JSON.stringify(selector) + ')'
  const click = selector => evaluate(query(selector) + '.click()')
  const expect = (expression, label) => wait(window, expression, label)
  const shots = path.resolve(__dirname, '../output/mcp-preview')
  await fs.mkdir(shots, { recursive: true })
  const capture = async name => {
    await evaluate('Promise.all(document.getAnimations().filter(a => a.effect?.getTiming().iterations !== Infinity).map(a => a.finished.catch(() => {}))) .then(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve(true)))))')
    const { data } = await window.webContents.debugger.sendCommand('Page.captureScreenshot', { format: 'png' })
    await fs.writeFile(path.join(shots, name + '.png'), Buffer.from(data, 'base64'))
  }
  window.webContents.debugger.attach()
  const open = async () => {
    await evaluate(query('.mcp-entry button') + '.scrollIntoView({block:"center"})')
    await click('.mcp-entry button')
    await expect(query('.mcp-panel') + ' !== null', 'MCP list opened')
  }
  await open()
  await click('.mcp-empty button')
  await setValue('.mcp-field input', 'figma_bridge')
  await setValue('.mcp-field input[type=url]', 'http://127.0.0.1:3333/mcp')
  await click('.mcp-pairs summary')
  await click('.mcp-pairs .mcp-text')
  await setValue('.mcp-pair-row input', 'Authorization')
  await setValue('.mcp-pair-row input[type=password]', 'demo-value')
  await click('.mcp-form [type=submit]')
  await expect(query('.mcp-list strong') + '?.textContent === "figma_bridge"', 'HTTP service added')
  await click('.mcp-list .mcp-icon')
  await setValue('input[type=url]', 'https://example.invalid/cancel')
  await click('.mcp-form footer .mcp-btn[type=button]')
  await click('.mcp-list .mcp-icon')
  assert.equal(await evaluate(query('input[type=url]') + '.value'), 'http://127.0.0.1:3333/mcp')
  await capture('edit-http')
  await setValue('input[type=url]', 'https://example.invalid/changed')
  await click('.mcp-form [type=submit]')
  await click('.mcp-list .mcp-icon')
  assert.equal(await evaluate(query('input[type=url]') + '.value'), 'https://example.invalid/changed')
  await click('.mcp-form footer .mcp-btn[type=button]')
  await click('.mcp-list-head button')
  await setValue('.mcp-field input', 'figma_bridge')
  await click('.mcp-method label:last-child input')
  await click('.mcp-args .mcp-text')
  await setValue('.mcp-arg-row input', '@playwright/mcp')
  await click('.mcp-form [type=submit]')
  await expect(query('.mcp-error') + ' !== null', 'duplicate service rejected')
  await setValue('.mcp-field input', 'playwright')
  await capture('add-stdio')
  await click('.mcp-form [type=submit]')
  await expect('document.querySelectorAll(".mcp-list li").length === 2', 'stdio service added')
  await click('.mcp-list li:last-child [role=switch]')
  await expect(query('.mcp-list li:last-child [role=switch]') + '?.getAttribute("aria-checked") === "false"', 'service disabled')
  await capture('services')
  await click('.mcp-panel footer button')
  await expect(query('.mcp-panel') + ' === null', 'MCP list closed')
  await capture('settings')
  await click('[aria-label="关闭办公室设置"]')
  await click('[aria-label="打开办公室设置"]')
  await selectLanguage('en')
  await expect(query('.mcp-entry small') + '?.textContent === "1 of 2 enabled"', 'settings reopen in English with preview choices intact')
  await open()
  await click('.mcp-list li:last-child .mcp-icon')
  assert.equal(await evaluate(query('.mcp-arg-row input') + '.value'), '@playwright/mcp')
  assert.equal(await evaluate(query('#mcp-title') + '.textContent'), 'Edit service')
  await click('.mcp-panel header .mcp-icon:last-child')
  await expect(query('.mcp-panel') + ' === null', 'MCP form closed')
  await selectLanguage('zh-CN')
  const closeSettings = () => click('[aria-label="关闭办公室设置"]')
  const globalList = async () => { await click('[aria-label="打开办公室设置"]'); await open() }
  const leaveList = async () => {
    await expect(query('.mcp-list-head') + ' !== null && !document.querySelector(".mcp-panel fieldset[disabled]")', 'service change saved')
    await click('.mcp-panel footer button')
    await expect(query('.mcp-panel') + ' === null', 'list closed')
    await closeSettings()
  }
  const selectEmployee = async id => {
    await click('[data-edit-employee-item="' + id + '"]')
    await expect(query('[data-edit-employee-mcp]') + ' !== null && ' + query('[data-save-employee]') + '?.disabled === false', 'employee settings loaded')
  }
  const employeeEditor = async () => {
    await click('[data-office-employee-editor-launcher]')
    await expect(query('[data-edit-employee-item="frontend-one"]') + ' !== null', 'editor opened')
    await selectEmployee('frontend-one')
  }
  const option = '[data-edit-mcp="figma_bridge"]'
  await closeSettings()
  await employeeEditor()
  assert.equal(await evaluate(query('[data-edit-mcp="playwright"]')), null)
  await click(option)
  await click('[data-save-employee]')
  await click('[data-close-employee-editor]')
  await employeeEditor()
  assert.equal(await evaluate(query(option) + '.checked'), true)
  await evaluate(query(option) + '.scrollIntoView({block:"center"})')
  await capture('employee-mcp')
  await selectEmployee('research-one')
  assert.equal(await evaluate(query(option) + '.checked'), false)
  await click(option)
  await click('[data-close-employee-editor]')
  await employeeEditor()
  await selectEmployee('research-one')
  assert.equal(await evaluate(query(option) + '.checked'), false)
  await click('[data-close-employee-editor]')
  await globalList()
  await click('[role=switch][aria-label=figma_bridge]')
  await leaveList()
  await employeeEditor()
  assert.equal(await evaluate(query(option)), null)
  await click('[data-close-employee-editor]')
  await globalList()
  await click('[role=switch][aria-label=figma_bridge]')
  await leaveList()
  await employeeEditor()
  assert.equal(await evaluate(query(option) + '.checked'), false)
  await click(option)
  await click('[data-save-employee]')
  await click('[data-close-employee-editor]')
  await globalList()
  await click('.mcp-list li:first-child .mcp-icon')
  await click('.mcp-remove')
  await leaveList()
  await employeeEditor()
  assert.equal(await evaluate(query(option)), null)
  await click('[data-close-employee-editor]')
  await globalList()
  await click('.mcp-list-head button')
  await setValue('.mcp-field input', 'figma_bridge')
  await setValue('.mcp-field input[type=url]', 'http://127.0.0.1:4444/mcp')
  await click('.mcp-form [type=submit]')
  await leaveList()
  await employeeEditor()
  assert.equal(await evaluate(query(option) + '.checked'), false)
  window.webContents.debugger.detach()
  console.log('MCP_SETTINGS_SMOKE_OK')
}
